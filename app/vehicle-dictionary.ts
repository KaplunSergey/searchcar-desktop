function lookup(table: Record<string, Translation>, value: unknown, locale: Locale): string | null {
  if (value === null || value === undefined || value === "") return null;
  const raw = String(value).trim();
  return table[raw]?.[locale === "uk" ? 1 : 0] || raw;
}

export function translateVehicleSpec(
  kind: "type" | "fuel" | "transmission" | "color",
  value: unknown,
  locale: Locale,
): string | null {
  return lookup({ type: vehicleType, fuel, transmission, color }[kind], value, locale);
}

export function translateOptionCode(code: string, locale: Locale): string {
  const entry = options[code];
  return entry ? entry[locale === "uk" ? 2 : 1] : `Encar ${code}`;
}

export function formatSeatCount(value: unknown, locale: Locale): string | null {
  const count = Number(value);
  if (!Number.isInteger(count) || count < 1 || count > 30) return null;
  const end = count % 10;
  const teen = count % 100 >= 11 && count % 100 <= 14;
  const noun = locale === "uk"
    ? !teen && end === 1 ? "місце" : !teen && end >= 2 && end <= 4 ? "місця" : "місць"
    : !teen && end === 1 ? "место" : !teen && end >= 2 && end <= 4 ? "места" : "мест";
  return `${count} ${noun}`;
}
